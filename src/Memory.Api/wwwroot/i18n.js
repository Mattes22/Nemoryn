let currentLocale = detectLocale();

function detectLocale() {
  const stored = localStorage.getItem(I18N_STORAGE_KEY);
  if (I18N_SUPPORTED.includes(stored)) {
    return stored;
  }

  return "en";
}

function t(key, vars) {
  const dict = I18N_STRINGS[currentLocale] || I18N_STRINGS.en;
  let text = dict[key] ?? I18N_STRINGS.en[key] ?? I18N_STRINGS.cs[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value ?? ""));
    }
  }
  return text;
}

function localeTag() {
  return I18N_TAGS[currentLocale] || "en-US";
}

function applyStaticI18n() {
  document.documentElement.lang = currentLocale;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
  const select = document.querySelector("#locale-select");
  if (select) {
    select.value = currentLocale;
  }
}

function setLocale(locale) {
  if (!I18N_SUPPORTED.includes(locale) || locale === currentLocale) {
    return false;
  }

  currentLocale = locale;
  localStorage.setItem(I18N_STORAGE_KEY, locale);
  applyStaticI18n();
  return true;
}

applyStaticI18n();
